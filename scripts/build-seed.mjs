// Turns supabase/seed-source.mjs into:
//   supabase/seed.sql                 – a fresh database: run after the migrations
//   supabase/updates/deck-update.sql  – a database already in use: brings the deck's
//                                       projects up to date (see the note at its top)
//   lib/seed.generated.json           – the same data, used when Supabase isn't connected
// IDs are derived from names, so re-running gives the same rows.
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import * as src from '../supabase/seed-source.mjs';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));

const uuid = (key) => {
  const h = createHash('sha1').update(`collabstudio:${key}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (ids) => `'{${ids.join(',')}}'::uuid[]`;
const now = new Date('2026-11-17T00:00:00Z').toISOString();

const clients = src.clients.map((name, i) => ({ id: uuid(`client:${name}`), name, logo_url: null, logo_path: null, sort_order: i }));
const categories = src.categories.map((name, i) => ({ id: uuid(`category:${name}`), name, sort_order: i }));
const tags = [
  ...src.capabilities.map((name, i) => ({ id: uuid(`capability:${name}`), name, type: 'capability', sort_order: i })),
  ...src.tools.map((name, i) => ({ id: uuid(`tool:${name}`), name, type: 'tool', sort_order: i })),
];
const idOf = (list, name, kind) => {
  const row = list.find((r) => r.name === name && (!kind || r.type === kind));
  if (!row) throw new Error(`Unknown ${kind ?? 'name'}: ${name}`);
  return row.id;
};

const projects = [];
const blocks = [];
const items = [];
const media = [];
let featuredOrder = 0;

src.projects.forEach((p, i) => {
  const id = uuid(`project:${p.slug}`);
  // The key `cover` keeps the id earlier seeds gave the cover, so updates replace it in place.
  const mediaId = (key) => uuid(`media:${p.slug}:${key}`);
  (p.media ?? []).forEach((m, j) =>
    media.push({ id: mediaId(m.key), project_id: id, kind: m.kind, url: m.src, storage_path: null, aspect: m.aspect, caption: m.caption ?? null, sort_order: j, created_at: now }),
  );
  const coverId = p.cover ? mediaId(p.cover) : null;
  const heroId = p.hero ? mediaId(p.hero) : coverId;
  projects.push({
    id,
    slug: p.slug,
    title: p.title,
    client_ids: p.clients.map((n) => idOf(clients, n)),
    category_ids: p.categories.map((n) => idOf(categories, n)),
    tag_ids: [...p.capabilities.map((n) => idOf(tags, n, 'capability')), ...p.tools.map((n) => idOf(tags, n, 'tool'))],
    year: p.year,
    status: p.status,
    status_note: p.status_note ?? null,
    one_liner: p.one_liner,
    about: p.about ?? null,
    output_summary: p.output_summary,
    capabilities_summary: p.capabilities_summary,
    workflow_label: p.workflow_label ?? null,
    featured: p.featured,
    featured_order: p.featured ? featuredOrder++ : 0,
    sort_order: i,
    visibility: 'published',
    is_internal: p.is_internal,
    cover_media_id: coverId,
    hero_media_id: heroId,
    // Names, for the update file (a live database may hold its own ids for these).
    _clients: p.clients,
    _categories: p.categories,
    _capabilities: p.capabilities,
    _tools: p.tools,
    created_at: now,
    updated_at: now,
    deleted_at: null,
  });
  p.blocks.forEach(([label, body], j) => blocks.push({ id: uuid(`block:${p.slug}:${j}`), project_id: id, label, body, sort_order: j }));
  p.deliverables.forEach((text, j) => items.push({ id: uuid(`deliverable:${p.slug}:${j}`), project_id: id, type: 'deliverable', text, sort_order: j }));
  p.ai_workflow.forEach((text, j) => items.push({ id: uuid(`workflow:${p.slug}:${j}`), project_id: id, type: 'ai_workflow', text, sort_order: j }));
});

const settings = Object.entries(src.settings).map(([key, value]) => ({ key, value }));

// --- SQL ---
const sql = [];
sql.push('-- Generated by scripts/build-seed.mjs from supabase/seed-source.mjs. Safe to re-run.');
sql.push('begin;');
for (const c of clients) sql.push(`insert into public.clients (id, name, sort_order) values (${q(c.id)}, ${q(c.name)}, ${c.sort_order}) on conflict (id) do nothing;`);
for (const c of categories) sql.push(`insert into public.categories (id, name, sort_order) values (${q(c.id)}, ${q(c.name)}, ${c.sort_order}) on conflict (id) do nothing;`);
for (const t of tags) sql.push(`insert into public.tags (id, name, type, sort_order) values (${q(t.id)}, ${q(t.name)}, ${q(t.type)}, ${t.sort_order}) on conflict (id) do nothing;`);
for (const p of projects) {
  sql.push(
    `insert into public.projects (id, slug, title, client_ids, category_ids, tag_ids, year, status, status_note, one_liner, about, output_summary, capabilities_summary, workflow_label, featured, featured_order, sort_order, visibility, is_internal) values (` +
      [q(p.id), q(p.slug), q(p.title), arr(p.client_ids), arr(p.category_ids), arr(p.tag_ids), p.year, q(p.status), q(p.status_note), q(p.one_liner), q(p.about), q(p.output_summary), q(p.capabilities_summary), q(p.workflow_label), p.featured, p.featured_order, p.sort_order, q(p.visibility), p.is_internal].join(', ') +
      ') on conflict (id) do nothing;',
  );
}
for (const m of media) sql.push(`insert into public.media (id, project_id, kind, url, aspect, caption, sort_order) values (${q(m.id)}, ${q(m.project_id)}, ${q(m.kind)}, ${q(m.url)}, ${q(m.aspect)}, ${q(m.caption)}, ${m.sort_order}) on conflict (id) do nothing;`);
for (const p of projects) if (p.cover_media_id) sql.push(`update public.projects set cover_media_id = ${q(p.cover_media_id)}, hero_media_id = ${q(p.hero_media_id)} where id = ${q(p.id)} and cover_media_id is null;`);
for (const b of blocks) sql.push(`insert into public.overview_blocks (id, project_id, label, body, sort_order) values (${q(b.id)}, ${q(b.project_id)}, ${q(b.label)}, ${q(b.body)}, ${b.sort_order}) on conflict (id) do nothing;`);
for (const it of items) sql.push(`insert into public.list_items (id, project_id, type, text, sort_order) values (${q(it.id)}, ${q(it.project_id)}, ${q(it.type)}, ${q(it.text)}, ${it.sort_order}) on conflict (id) do nothing;`);
for (const s of settings) sql.push(`insert into public.settings (key, value) values (${q(s.key)}, ${q(JSON.stringify(s.value))}::jsonb) on conflict (key) do nothing;`);
sql.push('commit;');

writeFileSync(path.join(root, 'supabase/seed.sql'), sql.join('\n') + '\n');

// --- Update for a database already in use ---
// Lists are matched by name (the admin may have made its own rows), project
// content is replaced with the deck's, and media is added or refreshed by id.
// Featured, visibility and internal flags, and media added in the admin, are left alone.
const names = (list) => `array[${list.map(q).join(', ') || "''"}]::text[]`;
const idsByName = (table, list, type) =>
  list.length
    ? `coalesce((select array_agg(t.id order by x.o) from unnest(${names(list)}) with ordinality x(n, o) join public.${table} t on t.name = x.n${type ? ` and t.type = ${q(type)}` : ''}), '{}')`
    : `'{}'::uuid[]`;
const up = [];
up.push('-- Generated by scripts/build-seed.mjs from supabase/seed-source.mjs.');
up.push('-- Brings the deck projects in a live database up to date. Run after all migrations. Safe to re-run.');
up.push("-- Replaces each deck project's text, overview blocks, deliverables and AI steps, and sets its cover and hero.");
up.push('-- Keeps: featured, visibility, internal flags, and any media or projects added in the admin.');
up.push('begin;');
for (const c of clients) up.push(`insert into public.clients (id, name, sort_order) values (${q(c.id)}, ${q(c.name)}, ${c.sort_order}) on conflict do nothing;`);
for (const c of categories) up.push(`insert into public.categories (id, name, sort_order) values (${q(c.id)}, ${q(c.name)}, ${c.sort_order}) on conflict do nothing;`);
for (const t of tags) up.push(`insert into public.tags (id, name, type, sort_order) values (${q(t.id)}, ${q(t.name)}, ${q(t.type)}, ${t.sort_order}) on conflict do nothing;`);
for (const p of projects) {
  const tagIds = `${idsByName('tags', p._capabilities, 'capability')} || ${idsByName('tags', p._tools, 'tool')}`;
  up.push(
    `insert into public.projects (id, slug, title, client_ids, category_ids, tag_ids, year, status, status_note, one_liner, about, output_summary, capabilities_summary, workflow_label, featured, featured_order, sort_order, visibility, is_internal) values (` +
      [q(p.id), q(p.slug), q(p.title), idsByName('clients', p._clients), idsByName('categories', p._categories), tagIds, p.year, q(p.status), q(p.status_note), q(p.one_liner), q(p.about), q(p.output_summary), q(p.capabilities_summary), q(p.workflow_label), p.featured, p.featured_order, p.sort_order, q(p.visibility), p.is_internal].join(', ') +
      ') on conflict (id) do update set slug = excluded.slug, title = excluded.title, client_ids = excluded.client_ids, category_ids = excluded.category_ids, tag_ids = excluded.tag_ids, year = excluded.year, status = excluded.status, status_note = excluded.status_note, one_liner = excluded.one_liner, about = excluded.about, output_summary = excluded.output_summary, capabilities_summary = excluded.capabilities_summary, workflow_label = excluded.workflow_label, sort_order = excluded.sort_order;',
  );
}
const deckIds = projects.map((p) => q(p.id)).join(', ');
up.push(`delete from public.overview_blocks where project_id in (${deckIds});`);
up.push(`delete from public.list_items where project_id in (${deckIds});`);
for (const b of blocks) up.push(`insert into public.overview_blocks (id, project_id, label, body, sort_order) values (${q(b.id)}, ${q(b.project_id)}, ${q(b.label)}, ${q(b.body)}, ${b.sort_order});`);
for (const it of items) up.push(`insert into public.list_items (id, project_id, type, text, sort_order) values (${q(it.id)}, ${q(it.project_id)}, ${q(it.type)}, ${q(it.text)}, ${it.sort_order});`);
for (const m of media) up.push(`insert into public.media (id, project_id, kind, url, aspect, caption, sort_order) values (${q(m.id)}, ${q(m.project_id)}, ${q(m.kind)}, ${q(m.url)}, ${q(m.aspect)}, ${q(m.caption)}, ${m.sort_order}) on conflict (id) do update set kind = excluded.kind, url = excluded.url, storage_path = null, aspect = excluded.aspect, caption = excluded.caption, sort_order = excluded.sort_order;`);
for (const p of projects) up.push(`update public.projects set cover_media_id = ${q(p.cover_media_id)}, hero_media_id = ${q(p.hero_media_id)} where id = ${q(p.id)};`);
for (const s of settings) up.push(`insert into public.settings (key, value) values (${q(s.key)}, ${q(JSON.stringify(s.value))}::jsonb) on conflict (key) do nothing;`);
up.push('commit;');
mkdirSync(path.join(root, 'supabase/updates'), { recursive: true });
writeFileSync(path.join(root, 'supabase/updates/deck-update.sql'), up.join('\n') + '\n');

const strip = (p) => Object.fromEntries(Object.entries(p).filter(([k]) => !k.startsWith('_')));
writeFileSync(
  path.join(root, 'lib/seed.generated.json'),
  JSON.stringify({ clients, categories, tags, projects: projects.map(strip), overview_blocks: blocks, list_items: items, media, settings }, null, 2) + '\n',
);
console.log(`Seed: ${projects.length} projects, ${clients.length} clients, ${tags.length} tags.`);
